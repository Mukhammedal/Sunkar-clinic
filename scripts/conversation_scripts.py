def get_script(lang: str, key: str, **kwargs) -> str:
    """Получить текст скрипта с подстановкой переменных."""
    lang = lang if lang in SCRIPTS else "ru"
    text = SCRIPTS[lang].get(key, SCRIPTS["ru"].get(key, ""))
    if kwargs:
        try:
            text = text.format(**kwargs)
        except KeyError:
            pass
    return text


